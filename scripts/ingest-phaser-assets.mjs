async function main() {
  console.log(`🎮 Ingesting ${PHASER_ASSETS.length} official Phaser assets into PostgreSQL...`);
  const client = await pool.connect();
  try {
    let inserted = 0;
    for (const a of PHASER_ASSETS) {
      await client.query(`
        INSERT INTO community_assets (id, title, category, style, tags, image_url, thumbnail_url, uses_count, is_transparent, is_system)
        VALUES ($1, $2, $3, $4, $5, $6, $7, $8, TRUE, TRUE)
        ON CONFLICT (id) DO UPDATE SET
          title = EXCLUDED.title,
          category = EXCLUDED.category,
          style = EXCLUDED.style,
          tags = EXCLUDED.tags,
          image_url = EXCLUDED.image_url,
          thumbnail_url = EXCLUDED.thumbnail_url,
          uses_count = EXCLUDED.uses_count;
      `, [a.id, a.title, a.category, a.style, a.tags, a.image_url, a.thumbnail_url, a.uses_count]);
      inserted++;
    }
    console.log(`✅ Successfully ingested ${inserted} Phaser 2D arcade assets!`);
  } finally {
    client.release();
    await pool.end();
  }
}

main().catch((err) => {
  console.error('❌ Ingestion failed:', err);
  process.exit(1);
});
